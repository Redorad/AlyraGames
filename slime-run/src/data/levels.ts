import type { LevelData } from '../types'

function makeEnemy(
  x: number,
  y: number,
  type: 'direwolf' | 'orc' | 'shadow',
  patrolRange = 100,
  speed = 1
) {
  const emojis = { direwolf: '\u{1F43A}', orc: '\u{1F479}', shadow: '\u{1F47B}' }
  return {
    x,
    y,
    width: 32,
    height: 32,
    type,
    emoji: emojis[type],
    speed,
    patrolRange,
    originalX: x,
    direction: 1,
    alive: true,
  }
}

function makeCrystal(x: number, y: number) {
  return {
    x,
    y,
    width: 20,
    height: 20,
    type: 'crystal' as const,
    emoji: '\u2728',
    collected: false,
  }
}

function makeHeart(x: number, y: number) {
  return {
    x,
    y,
    width: 20,
    height: 20,
    type: 'heart' as const,
    emoji: '\u2764\uFE0F',
    collected: false,
  }
}

function makePlatform(
  x: number,
  y: number,
  width: number,
  height = 32,
  moving?: { range: number; speed: number; axis?: 'x' | 'y' }
) {
  return {
    x,
    y,
    width,
    height,
    moving: !!moving,
    moveRange: moving?.range ?? 0,
    moveSpeed: moving?.speed ?? 0,
    moveAxis: (moving?.axis ?? 'x') as 'x' | 'y',
    originalX: x,
    originalY: y,
  }
}

