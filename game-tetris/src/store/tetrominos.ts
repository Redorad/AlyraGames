export function getShape(type: TetrominoType, rotation: number): number[][] {
  return SHAPES[type][rotation % 4];
}

export function getWallKicks(type: TetrominoType, fromRot: number, toRot: number): [number, number][] {
  const key = `${fromRot}>${toRot}`;
  if (type === 'I') {
    return WALL_KICKS_I[key] || [[0, 0]];
  }
  return WALL_KICKS_JLSTZ[key] || [[0, 0]];
}

const BAG: TetrominoType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

export function generateBag(): TetrominoType[] {
  const bag = [...BAG];
  // Fisher-Yates shuffle
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  return bag;
}
